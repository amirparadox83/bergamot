/// داده‌های تمرینی Bergamot — نسخه curated (PHASE 10)
///
/// این فایل شامل metadata تمرین‌های اضافی برای توسعه Exercise Library است.
/// داده‌ها از منابع عمومی (مثل wger Wiki که CC-BY-SA است) و دانش عمومی
/// fitness industry الهام گرفته شده‌اند، ولی مقادیر خاص (کالری، مدت، reps)
/// rule-based و保守 هستند — نه AI.
///
/// هر تمرین دارای:
///   - normalizedNameEn: کلید برای dedup (اگر با تمرین موجود یکی باشد، skip می‌شود)
///   - primaryMuscle / secondaryMuscles: کدهای MuscleGroupRef
///   - tips / commonMistakes: نکات آموزشی فارسی
///   - caloriesEstimatePerRep: تخمین کالری به‌ازای هر تکرار (MET-based)
///
/// NO AI / NO ML — تمام مقادیر rule-based هستند.
library;

class CuratedExercise {
  final String nameEn;
  final String nameFa;
  final String category;          // legacy code
  final String equipment;          // legacy code
  final int difficulty;            // 1-3
  final String primaryMuscle;      // MuscleGroupRef.code
  final List<String> secondaryMuscles;
  final String exerciseType;      // 'rep_based' or 'time_based'
  final String instructionsFa;
  final String? tips;
  final String? commonMistakes;
  final int defaultSets;
  final int? defaultReps;
  final int? defaultDurationSeconds;
  final int restSeconds;
  final double? caloriesEstimatePerRep;
  final String externalId;        // 'BERGAMOT_CURATED:<nameEn_lower_snake>'

  const CuratedExercise({
    required this.nameEn,
    required this.nameFa,
    required this.category,
    required this.equipment,
    required this.difficulty,
    required this.primaryMuscle,
    this.secondaryMuscles = const [],
    this.exerciseType = 'rep_based',
    required this.instructionsFa,
    this.tips,
    this.commonMistakes,
    this.defaultSets = 3,
    this.defaultReps,
    this.defaultDurationSeconds,
    this.restSeconds = 60,
    this.caloriesEstimatePerRep,
  }) : externalId = '';

  /// شناسه externalId تولید شده از nameEn
  String get computedExternalId {
    final snake = nameEn.toLowerCase().replaceAll(RegExp(r'[^a-z0-9 ]'), '').replaceAll(' ', '_');
    return 'BERGAMOT_CURATED:$snake';
  }
}

